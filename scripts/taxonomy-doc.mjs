// Keeps NEW-IDEA-CHECKLIST.md in step with content/taxonomy.yml.
//   pnpm taxonomy        rewrites the generated block of the checklist
// The tests import renderDocument() and fail when the checklist on disk is out of date, so a topic
// cannot be added without the checklist being updated.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const root = new URL('../', import.meta.url)
export const DOC_URL = new URL('NEW-IDEA-CHECKLIST.md', root)
export const START = '<!-- taxonomy:start (generated by `pnpm taxonomy`, do not edit by hand) -->'
export const END = '<!-- taxonomy:end -->'

export function loadTaxonomy() {
  return parse(readFileSync(new URL('content/taxonomy.yml', root), 'utf8'))
}

/** The tables for every area: label, id and what each topic is for. */
export function renderTables(tax) {
  return tax.areas
    .map(a => [
      `### ${a.label} (\`${a.id}\`)`,
      '',
      a.about,
      '',
      '| Topic | id | Use it for |',
      '| --- | --- | --- |',
      ...a.topics.map(t => `| ${t.label} | \`${t.id}\` | ${t.about} |`),
      '',
    ].join('\n'))
    .join('\n')
}

/** Replaces the block between the markers and leaves everything else in the document alone. */
export function renderDocument(current, tax) {
  const start = current.indexOf(START)
  const end = current.indexOf(END)
  if (start < 0 || end < start) throw new Error('NEW-IDEA-CHECKLIST.md is missing its taxonomy markers')
  return current.slice(0, start + START.length) + '\n\n' + renderTables(tax) + '\n' + current.slice(end)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tax = loadTaxonomy()
  writeFileSync(DOC_URL, renderDocument(readFileSync(DOC_URL, 'utf8'), tax))
  console.log(`checklist updated: ${tax.areas.length} areas, ${tax.areas.reduce((n, a) => n + a.topics.length, 0)} topics`)
}
